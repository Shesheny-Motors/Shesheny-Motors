-- ==========================================
-- 3. Row Level Security (RLS) Policies
-- ==========================================

-- Enable RLS on all tables
ALTER TABLE public.vehicles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.inquiries ENABLE ROW LEVEL SECURITY;

-- Vehicles: Anyone can read, only authenticated users (admin) can insert/update/delete
CREATE POLICY "Allow public read access on vehicles" ON public.vehicles FOR SELECT USING (true);
CREATE POLICY "Allow auth insert on vehicles" ON public.vehicles FOR INSERT TO authenticated WITH CHECK (true);
CREATE POLICY "Allow auth update on vehicles" ON public.vehicles FOR UPDATE TO authenticated USING (true);
CREATE POLICY "Allow auth delete on vehicles" ON public.vehicles FOR DELETE TO authenticated USING (true);

-- Settings: Anyone can read, only authenticated users can update
CREATE POLICY "Allow public read access on settings" ON public.settings FOR SELECT USING (true);
CREATE POLICY "Allow auth update on settings" ON public.settings FOR UPDATE TO authenticated USING (true);
-- Prevent deletion/insertion of settings by anyone to protect the single row
CREATE POLICY "Prevent delete on settings" ON public.settings FOR DELETE USING (false);
CREATE POLICY "Prevent insert on settings" ON public.settings FOR INSERT WITH CHECK (false);

-- Inquiries: Anyone can insert (submit form), only authenticated can read/update/delete
CREATE POLICY "Allow public insert on inquiries" ON public.inquiries FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow auth read on inquiries" ON public.inquiries FOR SELECT TO authenticated USING (true);
CREATE POLICY "Allow auth update on inquiries" ON public.inquiries FOR UPDATE TO authenticated USING (true);
CREATE POLICY "Allow auth delete on inquiries" ON public.inquiries FOR DELETE TO authenticated USING (true);

-- ==========================================
-- 4. Storage Buckets Setup
-- ==========================================
-- Note: It is often easier to create buckets via the Supabase UI. 
-- However, running the below will create a public bucket named "vehicles" if it doesn't exist.

INSERT INTO storage.buckets (id, name, public)
VALUES ('vehicles', 'vehicles', true)
ON CONFLICT (id) DO NOTHING;

-- Storage RLS Policies
-- Allow public access to read images from the vehicles bucket
CREATE POLICY "Give public access to vehicles bucket" ON storage.objects FOR SELECT USING (bucket_id = 'vehicles');

-- Allow authenticated users to upload, update, and delete images in the vehicles bucket
CREATE POLICY "Allow auth upload to vehicles bucket" ON storage.objects FOR INSERT TO authenticated WITH CHECK (bucket_id = 'vehicles');
CREATE POLICY "Allow auth update to vehicles bucket" ON storage.objects FOR UPDATE TO authenticated USING (bucket_id = 'vehicles');
CREATE POLICY "Allow auth delete from vehicles bucket" ON storage.objects FOR DELETE TO authenticated USING (bucket_id = 'vehicles');
