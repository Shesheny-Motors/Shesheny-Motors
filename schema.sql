-- Shesheny Motors Supabase Schema

-- ==========================================
-- 1. Create Tables
-- ==========================================

-- Vehicles Table
CREATE TABLE public.vehicles (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL,
    brand text NOT NULL,
    model text NOT NULL,
    year integer NOT NULL,
    price_egp numeric NOT NULL,
    price_usd numeric NOT NULL,
    color text NOT NULL,
    condition text NOT NULL,
    hp text NOT NULL,
    acceleration numeric NOT NULL,
    miles integer NOT NULL,
    video_url text,
    thumbnail text NOT NULL,
    gallery text[] DEFAULT '{}'::text[],
    is_spotlight boolean DEFAULT false
);

-- Settings Table (Global Config)
CREATE TABLE public.settings (
    id integer PRIMARY KEY,
    whatsapp_number text,
    call_number text,
    map_embed text,
    event_theme text DEFAULT 'none',
    instagram text,
    facebook text,
    tiktok text,
    exchange_rate numeric DEFAULT 50.0,
    hero_image text
);

-- Inquiries Table
CREATE TABLE public.inquiries (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL,
    "firstName" text NOT NULL,
    "lastName" text NOT NULL,
    email text NOT NULL,
    phone text,
    "inquiryType" text NOT NULL,
    message text NOT NULL
);

